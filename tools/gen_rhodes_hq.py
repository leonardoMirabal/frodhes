"""The HQ Rhodes' dense velocity table (the Move only, FR_HQ; private plan 06 item 2) -> firmware/gen/hq/rh_hq_pulse.h

Classic plays the hammer force pulse blended from the two velocity layers around v (8 layers). Here the same per-key
Hertz hammer-tine contact that tools/gen_rhodes.py runs for those layers (tools/hammer.py, the same cases, window
rule and area resampling) is run at every velocity 1..127, so the HQ voice plays the exact contact at its own
velocity: no blend. The pulse shape and its rate are the contact's; the peak (RH_PAMP: the calibrated velocity law)
stays Classic's, so the levels and the calibration are kept. At the 8 layer velocities the shapes and rates equal
Classic's exactly (checked here: the generator stops otherwise).

    python3 tools/gen_rhodes_hq.py [--check]      (--check: compare with the committed header, write nothing)
"""
import hashlib
import os
import sys

import numpy as np

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import gen_rhodes as gr  # noqa: E402
import hammer as hm  # noqa: E402
import rhodes_pins as rp  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "firmware/gen/hq/rh_hq_pulse.h")
VS = list(range(1, 128))


def exact_pulses(p, k):
    """{v: (shape [64] int, prate Q12, peak force re the key's strongest anchor)} for every v 1..127: the rules of
    gen_rhodes.key_pulses_all (its anchors give the window ratio and the force scale)"""
    cases = gr.contact_cases(p, k, gr.V_ANCH + VS)
    res = hm.contact_batch(cases, fs=gr.FS, t_max=0.03)
    anch = dict(zip(gr.V_ANCH, res[:len(gr.V_ANCH)]))
    seg = {v: gr.contact_segments(anch[v]["F"]) for v in gr.V_ANCH}
    ratio = min(8.0, max(sg[-1][1] / sg[0][1] for sg in seg.values()))
    fmax = max(anch[v]["F"].max() for v in gr.V_ANCH)
    dt = anch[gr.V_ANCH[0]]["dt"]
    out = {}
    for v, r in zip(VS, res[len(gr.V_ANCH):]):
        win = ratio * gr.contact_segments(r["F"])[0][1]
        nn = max(2, int(round(win)))
        F = np.concatenate([r["F"], np.zeros(max(0, nn - len(r["F"])))])[:nn]
        prate = int(round(64.0 / (win * dt * gr.FS) * gr.Q12))
        out[v] = (gr.area_resample(F), prate, float(r["F"].max() / fmax))
    return out


def physics():
    p = gr.load_params()
    gr.PINS = rp.load(p)
    Ls = gr.tine_lengths()
    phys = {n: gr.key_physics(p, n, Ls[n]) for n in range(gr.KEY_LO, gr.KEY_HI + 1)}
    for k in phys.values():
        k["off"] = gr.pickup_off(p, k["fam"])
    return p, phys


def build():
    import json
    spec = json.load(open(os.path.join(ROOT, "docs/model/data/rhodes_spec.json")))
    sk = {k["midi"]: k for k in spec["keys"]}
    p, phys = physics()
    shapes, prates = [], []
    for n in range(gr.KEY_LO, gr.KEY_HI + 1):
        ex = exact_pulses(p, phys[n])
        cl = sk[n]["pulse"]
        for li, v in enumerate(gr.LAYER_V):                 # the layers: Classic's numbers exactly
            assert ex[v][0] == cl["shapes"][li], (n, v, "shape")
            assert ex[v][1] == cl["prate"][gr.V_ANCH.index(v)], (n, v, "prate")
        shapes.append([ex[v][0] for v in VS])
        prates.append([ex[v][1] for v in VS])
        print(f"key {n}", file=sys.stderr, end="\r")
    return shapes, prates


def emit(shapes, prates):
    L = ["/* SPDX-License-Identifier: GPL-3.0-only */",
         "/* GENERATED by tools/gen_rhodes_hq.py from docs/model/data/params.json - do not edit. The HQ Rhodes' dense",
         " * velocity table (FR_HQ, the Move): the exact hammer contact's pulse shape and rate at every velocity 1..127",
         " * (row v - 1); the peak stays Classic's (RH_PAMP). Equal to RH_PULSE / RH_PRATE at the layer velocities */",
         "static const int16_t RH_HQ_PULSE[RH_NKEY][127][RH_PLEN + 2] = {"]
    for ks in shapes:
        L.append("{" + ",".join("{" + ",".join(map(str, sh)) + ",0,0}" for sh in ks) + "},")
    L.append("};")
    L.append("static const uint32_t RH_HQ_PRATE[RH_NKEY][127] = {   /* Q12 */")
    for kr in prates:
        assert all(0 < q < 2 ** 20 for q in kr), kr
        L.append("{" + ",".join(map(str, kr)) + "},")
    L.append("};")
    body = "\n".join(L) + "\n"
    return body + f"/* sha256(body) = {hashlib.sha256(body.encode()).hexdigest()} */\n"


def main():
    hdr = emit(*build())
    if "--check" in sys.argv[1:]:
        old = open(OUT).read() if os.path.exists(OUT) else ""
        print("equal" if old == hdr else "DIFFERS")
        return 0 if old == hdr else 1
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    open(OUT, "w").write(hdr)
    print(f"wrote {OUT} ({len(hdr)} bytes)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
