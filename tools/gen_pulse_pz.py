"""firmware/gen/pulse_pz.h from firmware/gen/rhodes_tables.h and bars_tables.h: the hammer / mallet pulse banks
(RH_PULSE, BAR_PULSE) packed losslessly for the flash (2026-11-01, the core-1 flash hunt).

Format "PZ", one stream of int16 words per pulse (64 points; the two pad points are always 0 and not stored): the
third difference of the points (x[-1] = x[-2] = x[-3] = 0), the head (up to the last value an int8 cannot hold) as
int16 words, the tail as int8, two to a word (little endian). No escapes, so the C decoder (rhodes.c rh_pz) is two
branch-free loops, a load and three adds a point: a pulse decodes at the strike in ~2 us (into the voice's pbuf, as
the layer crossfade always did). The Python decoder below checks every pulse round trip before the header is
written. Per bank: the streams back to back, each pulse's offset (uint16, in words) and head length (uint8). The bars' thump (the damper's knock, BAR_PULSE[pb][0][0], read at the key-up) stays raw:
BAR_THUMP[pb]. Rerun after tools/gen_rhodes.py or tools/gen_bars.py:

  tools/gen_pulse_pz.py           write the header
  tools/gen_pulse_pz.py --check   exit 1 if the header is not what the tables give (tests/py/test_gen_pulse_pz.py)
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RH = ROOT / "firmware" / "gen" / "rhodes_tables.h"
BA = ROOT / "firmware" / "gen" / "bars_tables.h"
OUT = ROOT / "firmware" / "gen" / "pulse_pz.h"
NPT = 64                                            # stored points (RH_PLEN, BAR_PLEN); + 2 pad points, always 0


def bank(path, name):
    """the pulses of a generated int16 table, each 66 points"""
    s = path.read_text()
    i = s.index("static const int16_t " + name + "[")
    j = s.index("= {", i) + 2
    k = s.index("};", j)
    v = [int(x) for x in re.findall(r"-?\d+", re.sub(r"/\*.*?\*/", "", s[j:k], flags=re.S))]
    assert len(v) % (NPT + 2) == 0, name
    p = [v[n:n + NPT + 2] for n in range(0, len(v), NPT + 2)]
    assert all(q[NPT] == 0 and q[NPT + 1] == 0 for q in p), name + ": a pad point is not 0"
    return p


def define(path, name):
    return int(re.search(r"#define " + name + r" (\d+)", path.read_text()).group(1))


def encode(x):
    """the third differences (x[-1] = x[-2] = x[-3] = 0), split: the head (up to the last one an int8 cannot hold) as
    int16, the tail as int8"""
    r, a, b, c = [], 0, 0, 0                        # x[i-1], x[i-2], x[i-3]
    for v in x[:NPT]:
        r.append(v - 3 * a + 3 * b - c)
        a, b, c = v, a, b
    n = max([i + 1 for i, v in enumerate(r) if not -128 <= v <= 127] or [0])
    assert all(-32768 <= v <= 32767 for v in r[:n])
    return r[:n], r[n:]


def words(head, tail):
    """a pulse's stream as int16 words: the head, then the tail bytes two to a word (little endian, padded with 0)"""
    t = [v & 255 for v in tail] + [0] * (len(tail) & 1)
    w = list(head) + [t[i] | t[i + 1] << 8 for i in range(0, len(t), 2)]
    return [v - 65536 if v >= 32768 else v for v in w]


def decode(w, n):
    """the C decoder (rhodes.c rh_pz) on the int16 words: n head words, then int8s; d2 += r; d1 += d2; x += d1"""
    by = [b for v in w[n:] for b in (v & 255, (v >> 8) & 255)]
    r = list(w[:n]) + [b - 256 if b >= 128 else b for b in by][:NPT - n]
    x, d1, d2, out = 0, 0, 0, []
    for v in r:
        d2 += v
        d1 += d2
        x += d1
        out.append(x)
    return out + [0, 0]


def pack(pulses):
    data, off, nh = [], [], []
    for p in pulses:
        h, t = encode(p)
        w = words(h, t)
        assert decode(w, len(h)) == p, "a pulse does not round-trip"
        off.append(len(data))
        nh.append(len(h))
        data += w
    assert len(data) < 65536
    return data, off, nh


def rows(vals, per, ind="    "):
    return [ind + ",".join(str(v) for v in vals[i:i + per]) + "," for i in range(0, len(vals), per)]


def header():
    rp, bp = bank(RH, "RH_PULSE"), bank(BA, "BAR_PULSE")
    nf, nl = define(BA, "BAR_NFAM"), define(BA, "BAR_NLAYER")
    assert len(rp) == define(RH, "RH_NKEY") * define(RH, "RH_NLAYER") and len(bp) == define(BA, "BAR_NPULSE") * nf * nl
    rd, ro, rn = pack(rp)
    bd, bo, bn = pack(bp)
    L = ["/* SPDX-License-Identifier: GPL-3.0-only */",
         "/* GENERATED by tools/gen_pulse_pz.py from firmware/gen/rhodes_tables.h and bars_tables.h - do not edit. */",
         "/* the pulse banks packed (PZ: per pulse the 3rd difference of its 64 points, the head as int16 and the tail as",
         " * int8, two to a word; rhodes.c rh_pz decodes one); pulses in order: RH [key][layer], BAR [band][family][layer] */",
         "#ifndef PULSE_PZ_H", "#define PULSE_PZ_H",
         "typedef struct {",
         "    const int16_t *d;      /* the streams */",
         "    const uint16_t *off;   /* per pulse: its stream (words) */",
         "    const uint8_t *nh;     /* per pulse: its int16 head (points) */",
         "} pz_bank_t;",
         f"/* RH_PULSE {len(rp) * 132} B -> {2 * len(rd)} + {3 * len(ro)} B */",
         f"static const int16_t RH_PZ[{len(rd)}] = {{", *rows(rd, 24), "};",
         f"static const uint16_t RH_PZ_OFF[{len(ro)}] = {{", *rows(ro, 20), "};",
         f"static const uint8_t RH_PZ_NH[{len(rn)}] = {{", *rows(rn, 32), "};",
         "static const pz_bank_t RH_PZB = {RH_PZ, RH_PZ_OFF, RH_PZ_NH};",
         f"/* BAR_PULSE {len(bp) * 132} B -> {2 * len(bd)} + {3 * len(bo)} B, + the thumps raw {len(bp) // (nf * nl) * 132} B */",
         f"static const int16_t BAR_PZ[{len(bd)}] = {{", *rows(bd, 24), "};",
         f"static const uint16_t BAR_PZ_OFF[{len(bo)}] = {{", *rows(bo, 20), "};",
         f"static const uint8_t BAR_PZ_NH[{len(bn)}] = {{", *rows(bn, 32), "};",
         "static const pz_bank_t BAR_PZB = {BAR_PZ, BAR_PZ_OFF, BAR_PZ_NH};",
         f"static const int16_t BAR_THUMP[{len(bp) // (nf * nl)}][{NPT + 2}] = {{   /* BAR_PULSE[pb][0][0]: the softest layer */"]
    for pb in range(len(bp) // (nf * nl)):
        L.append("    {" + ",".join(str(v) for v in bp[pb * nf * nl]) + "},")
    L += ["};", "#endif", ""]
    return "\n".join(L)


def main():
    h = header()
    if "--check" in sys.argv[1:]:
        ok = OUT.exists() and OUT.read_text() == h
        print("pulse_pz.h: " + ("current" if ok else "OUT OF DATE (run tools/gen_pulse_pz.py)"))
        return 0 if ok else 1
    OUT.write_text(h)
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
