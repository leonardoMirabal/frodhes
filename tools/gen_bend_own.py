"""Pitch-bend table, from its definition: the wheel spans +-2 semitones in quarter-semitone steps (k = -8..8, 48
steps per octave), each entry the frequency ratio minus one in Q30: round((2^(k/48) - 1) * 2^30).
Writes firmware/src/bend_own.h (BEND_OWN_T, 17 entries); engine.c interpolates between neighbours."""
import os
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
STEPS_PER_OCT = 48
RANGE_STEPS = 8          # +-2 semitones = +-8 quarter semitones
Q = 30


def table():
    out = []
    for k in range(-RANGE_STEPS, RANGE_STEPS + 1):
        x = (2.0 ** (k / STEPS_PER_OCT) - 1.0) * (1 << Q)
        assert abs((x % 1.0) - 0.5) > 0.01, "rounding too close to a tie for a float computation"
        out.append(int(round(x)))
    return out


def render():
    t = table()
    rows = [", ".join(str(v) for v in t[i:i + 9]) for i in range(0, len(t), 9)]
    return ("/* SPDX-License-Identifier: GPL-3.0-only */\n"
            "/* generated by tools/gen_bend_own.py: Q30 2^(k/48) - 1, k = -8..8 (quarter semitones, +-2 semitones) */\n"
            "static const int32_t BEND_OWN_T[17] = {\n    " + ",\n    ".join(rows) + "};\n")


if __name__ == "__main__":
    path = os.path.join(ROOT, "firmware", "src", "bend_own.h")
    if len(sys.argv) > 1 and sys.argv[1] == "--check":
        sys.exit(0 if open(path).read() == render() else 1)
    open(path, "w").write(render())
