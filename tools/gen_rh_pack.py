"""firmware/gen/rh_pack.h from rh_drive_mk.h, rh_velmap_mk.h and rh_tone_g.h: the Rhodes' level tables the firmware
links, with each distinct row stored once (0.9.13, the flash hunt). The three generated headers stay the contract
(their calibrators write them; what the tests and tools read); the originals are not linked.

 RH_MK_U, RH_DRV_MK_I[type][key]                       the drive's make-up rows (RH_MK_N anchors): RH_DRV_MK[t][k] is
                                                        RH_MK_U[RH_DRV_MK_I[t][k]]
 RH_VMK_U, RH_VM_MK_I[key]                             the MAP's, the same way (own rows: the FM-1 does not link them)
 RH_TW_U, RH_TONE_W_I[type][key]                      TONE's blend rows (RH_NANCH anchors), the same way

Rerun after tools/drive_makeup.py / velmap_makeup.py / tone_level.py --write (they do it themselves):

  tools/gen_rh_pack.py          write the header
  tools/gen_rh_pack.py --check  exit 1 if the header is not what the tables give (tests/py/test_gen_rh_pack.py)
"""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from gen_bars_pack import table  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
GEN = ROOT / "firmware" / "gen"
OUT = GEN / "rh_pack.h"


def rows_of(t):
    """the innermost rows of a nested list, in order, and the shape above them"""
    if t and isinstance(t[0], list):
        r, shape = [], [len(t)]
        for x in t:
            rr, ss = rows_of(x)
            r += rr
            sub = ss
        return r, shape + sub
    return [tuple(t)], []


def cv(v):
    return "{" + ",".join(cv(x) if isinstance(x, list) else str(x) for x in v) + "}"


def pool(tabs):
    """tabs: [(name, nested table)]; the distinct rows (first appearance) and, per table, the index in its shape"""
    rows, idx, out = {}, {}, []
    for name, t in tabs:
        r, shape = rows_of(t)
        ids = []
        for x in r:
            if x not in rows:
                rows[x] = len(out)
                out.append(x)
            ids.append(rows[x])
        assert len(out) < 256, "a uint8 index"
        it = iter(ids)

        def build(sh):
            return [next(it) for _ in range(sh[0])] if len(sh) == 1 else [build(sh[1:]) for _ in range(sh[0])]
        idx[name] = (shape, build(shape) if shape else ids[0])
    return out, idx


def header():
    def get(f, n):
        t = table((GEN / f).read_text(), n)
        assert t is not None, n
        return t
    mk, mi = pool([("RH_DRV_MK", get("rh_drive_mk.h", "RH_DRV_MK"))])
    vk, vi = pool([("RH_VM_MK", get("rh_velmap_mk.h", "RH_VM_MK"))])   # (its own rows: the FM-1 does not link the MAP's)
    tw, ti = pool([("RH_TONE_W", get("rh_tone_g.h", "RH_TONE_W"))])
    dm, vm, tn = mi["RH_DRV_MK"], vi["RH_VM_MK"], ti["RH_TONE_W"]
    return "\n".join([
        "/* SPDX-License-Identifier: GPL-3.0-only */",
        "/* GENERATED by tools/gen_rh_pack.py from rh_drive_mk.h, rh_velmap_mk.h and rh_tone_g.h - do not edit. */",
        "/* the Rhodes' level rows as linked: each distinct row once, a uint8 index per type / key */",
        "#ifndef RH_PACK_H", "#define RH_PACK_H",
        f"static const uint8_t RH_MK_U[{len(mk)}][RH_MK_N] = {{", *["    " + cv(r) + "," for r in mk], "};",
        f"static const uint8_t RH_DRV_MK_I[{dm[0][0]}][RH_NKEY] = {cv(dm[1])};",
        f"static const uint8_t RH_VMK_U[{len(vk)}][RH_MK_N] = {{", *["    " + cv(r) + "," for r in vk], "};",
        f"static const uint8_t RH_VM_MK_I[RH_NKEY] = {cv(vm[1])};",
        f"static const uint8_t RH_TW_U[{len(tw)}][RH_NANCH] = {{", *["    " + cv(r) + "," for r in tw], "};",
        f"static const uint8_t RH_TONE_W_I[{tn[0][0]}][RH_NKEY] = {cv(tn[1])};",
        "#endif", ""])


def main():
    h = header()
    if "--check" in sys.argv[1:]:
        ok = OUT.exists() and OUT.read_text() == h
        print("rh_pack.h: " + ("current" if ok else "OUT OF DATE (run tools/gen_rh_pack.py)"))
        return 0 if ok else 1
    OUT.write_text(h)
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
