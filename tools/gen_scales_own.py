"""Scale masks, from the interval lists: bit i of a mask is set when semitone i above the root is in the scale.
Writes firmware/src/scales_own.h (SCALE_OWN_MASK, same order as the SCALE page)."""
import os
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
SCALES = [
    ("MAJ", (0, 2, 4, 5, 7, 9, 11)), ("MIN", (0, 2, 3, 5, 7, 8, 10)), ("DOR", (0, 2, 3, 5, 7, 9, 10)),
    ("MIX", (0, 2, 4, 5, 7, 9, 10)), ("LYD", (0, 2, 4, 6, 7, 9, 11)), ("PHRY", (0, 1, 3, 5, 7, 8, 10)),
    ("HARM", (0, 2, 3, 5, 7, 8, 11)), ("MEL", (0, 2, 3, 5, 7, 9, 11)), ("PEN", (0, 2, 4, 7, 9)),
    ("MPEN", (0, 3, 5, 7, 10)), ("BLUES", (0, 3, 5, 6, 7, 10)),
]


def masks():
    return [sum(1 << i for i in iv) for _, iv in SCALES]


def render():
    body = "".join("    0x%03X, /* %s %s */\n" % (m, n, " ".join(map(str, iv))) for m, (n, iv) in zip(masks(), SCALES))
    return ("/* SPDX-License-Identifier: GPL-3.0-only */\n"
            "/* generated by tools/gen_scales_own.py: bit i = semitone i above the root is in the scale */\n"
            "static const uint16_t SCALE_OWN_MASK[11] = {\n" + body + "};\n")


if __name__ == "__main__":
    path = os.path.join(ROOT, "firmware", "src", "scales_own.h")
    if len(sys.argv) > 1 and sys.argv[1] == "--check":
        sys.exit(0 if open(path).read() == render() else 1)
    open(path, "w").write(render())
