"""firmware/gen/rhodes_phim.h from firmware/gen/rhodes_tables.h: the pickup's flux table and its slope interleaved,
RH_PHIM_n[2 i] = RH_PHI[f][i], RH_PHIM_n[2 i + 1] = RH_SLOPE[f][i] (the same values), one row per distinct
(Phi, slope) pair of rows and the pointer table RH_PHIM[fam]: family 0 (the 1/16" gap, keys <= 32 and >= 96,
R = 0.5) and family 1 (1/32", R = 1.0) are two rows (S8), families with equal tables would share one. The pickup's
Hermite reads p0, m0, p1, m1 from one base (rhodes.c rh_hermite_u). Rerun after tools/gen_rhodes.py:

  tools/gen_phim.py           write the header
  tools/gen_phim.py --check   exit 1 if the header is not what the tables give (tests/py/test_gen_phim.py)
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "firmware" / "gen" / "rhodes_tables.h"
OUT = ROOT / "firmware" / "gen" / "rhodes_phim.h"


def tables(text):
    """name -> (rows {index: [ints]}, pointer list [row index per family]) for RH_PHI and RH_SLOPE"""
    out = {}
    for name in ("RH_PHI", "RH_SLOPE"):
        rows = {int(m.group(1)): [int(v) for v in m.group(2).split(",")]
                for m in re.finditer(r"static const int32_t " + name + r"_(\d+)\[RH_PU_N \+ 1\] = \{([^}]*)\};", text)}
        m = re.search(r"static const int32_t \*const " + name + r"\[(\d+)\] = \{([^}]*)\};", text)
        ptr = [int(re.fullmatch(r"\s*" + name + r"_(\d+)\s*", p).group(1)) for p in m.group(2).split(",")]
        assert len(ptr) == int(m.group(1)) and all(len(r) == len(rows[0]) for r in rows.values())
        out[name] = (rows, ptr)
    return out


def header(text):
    t = tables(text)
    (prow, pptr), (srow, sptr) = t["RH_PHI"], t["RH_SLOPE"]
    assert len(pptr) == len(sptr)
    pairs, idx = [], []
    for f in range(len(pptr)):
        pr = (pptr[f], sptr[f])
        assert (prow[pptr[f]] == prow[pptr[0]]) == (srow[sptr[f]] == srow[sptr[0]]), "Phi and slope rows disagree"
        if pr not in pairs:
            pairs.append(pr)
        idx.append(pairs.index(pr))
    lines = ["/* SPDX-License-Identifier: GPL-3.0-only */",
             "/* GENERATED by tools/gen_phim.py from firmware/gen/rhodes_tables.h - do not edit. */",
             "/* the pickup table: Phi~ and its slope interleaved, [2 i] = RH_PHI[f][i], [2 i + 1] = RH_SLOPE[f][i] */",
             "#ifndef RHODES_PHIM_H", "#define RHODES_PHIM_H"]
    for j, (a, b) in enumerate(pairs):
        v = [x for pq in zip(prow[a], srow[b]) for x in pq]
        lines.append("static const int32_t RH_PHIM_%d[2 * (RH_PU_N + 1)] = {%s};" % (j, ",".join(map(str, v))))
    lines.append("static const int32_t *const RH_PHIM[%d] = {%s};" % (len(idx), ", ".join("RH_PHIM_%d" % i for i in idx)))
    lines.append("#endif")
    return "\n".join(lines) + "\n"


def main():
    want = header(SRC.read_text())
    if "--check" in sys.argv[1:]:
        ok = OUT.exists() and OUT.read_text() == want
        print("rhodes_phim.h", "up to date" if ok else "STALE: run tools/gen_phim.py")
        return 0 if ok else 1
    OUT.write_text(want)
    print("wrote", OUT.relative_to(ROOT))
    return 0


if __name__ == "__main__":
    sys.exit(main())
