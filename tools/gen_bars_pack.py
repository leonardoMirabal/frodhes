"""firmware/gen/bars_pack.h from firmware/gen/bars_tables.h: the bar tables the firmware links, packed losslessly for
the flash (0.9.13, the flash hunt). bars_tables.h stays the contract (the generator's output, what the tests and
tools read); the originals it holds that this header replaces are not linked (a static const nobody reads costs no
flash, as BAR_PULSE next to pulse_pz.h).

 BAR_KP[type][key]   BAR_KEYS without the 8th mode slot (X), which is all zero in every key of every type (28 B a
                     key); bars.c reads slot 7 as a zero mode (BAR_KM)
 BAR_GROW            the distinct 17-point gain rows of BAR_POSG and BAR_TUBEG (most of the TUBE rows are the flat
                     16384 row), each table now a uint8 row index: BAR_POSG_I[band][family], BAR_TUBEG_I[band][family]

  tools/gen_bars_pack.py [--src bars_tables.h] [--out DIR]   write the header
  tools/gen_bars_pack.py --check                              exit 1 if the header is not what the tables give
                                                              (tests/py/test_gen_bars_pack.py)
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "firmware" / "gen" / "bars_tables.h"
OUT = ROOT / "firmware" / "gen" / "bars_pack.h"
NMODE = 7                                           # stored slots; the 8th (BAR_NM - 1) is all zero


def table(text, name):
    """a generated table's numbers as nested lists (the braces kept)"""
    m = re.search(r"static const [\w ]+? " + name + r"((?:\[[^\]]*\])+) = \{", text)
    if not m:
        return None
    i = m.end() - 1
    d = 0
    j = i
    while True:
        c = text[j]
        d += (c == "{") - (c == "}")
        if d == 0:
            break
        j += 1
    st = [[]]
    for t in re.findall(r"\{|\}|-?\d+", re.sub(r"/\*.*?\*/", "", text[i:j + 1], flags=re.S)):
        if t == "{":
            st.append([])
        elif t == "}":
            x = st.pop()
            st[-1].append(x)
        else:
            st[-1].append(int(t))
    return st[0][0]


def define(text, name):
    m = re.search(r"#define " + name + r" (\d+)", text)
    return int(m.group(1)) if m else None


def cvals(v):
    return "{" + ",".join(cvals(x) if isinstance(x, list) else str(x) for x in v) + "}"


def header(text):
    keys = table(text, "BAR_KEYS")
    nt, nk, nm = define(text, "BAR_NTYPE"), define(text, "BAR_NKEY"), define(text, "BAR_NM")
    assert nm == NMODE + 1 and len(keys) == nt and all(len(t) == nk for t in keys)
    rows, pool = {}, []

    def row(r):
        t = tuple(r)
        if t not in rows:
            rows[t] = len(pool)
            pool.append(t)
        assert len(pool) < 256
        return rows[t]

    L = ["/* SPDX-License-Identifier: GPL-3.0-only */",
         "/* GENERATED by tools/gen_bars_pack.py from firmware/gen/bars_tables.h - do not edit. */",
         "/* the bar tables as linked (see the generator's header): BAR_KEYS without the all-zero 8th mode slot, and the",
         " * 17-point gain rows of BAR_POSG / BAR_TUBEG once each */",
         "#ifndef BARS_PACK_H", "#define BARS_PACK_H", f"#define BAR_NMK {NMODE}",
         f"static const bar_key_t BAR_KP[BAR_NTYPE][BAR_NKEY] = {{"]
    for t in keys:
        L.append("  {")
        for k in t:
            assert len(k[0]) == nm and all(v == 0 for v in k[0][NMODE]), "mode slot 7 is not all zero"
            L.append("    " + cvals([k[0][:NMODE]] + k[1:]) + ",")
        L.append("  },")
    L.append("};")
    idx = {}
    for nm_ in ("BAR_POSG", "BAR_TUBEG"):
        t = table(text, nm_)
        idx[nm_] = [[row(f) for f in band] for band in t]
    L.append(f"static const uint16_t BAR_GROW[{len(pool)}][BAR_NPOS] = {{")
    L += ["    {" + ",".join(map(str, r)) + "}," for r in pool]
    L.append("};")
    L.append("static const uint8_t BAR_POSG_I[BAR_NBAND][BAR_NFAM] = {" + ",".join(cvals(b) for b in idx["BAR_POSG"]) + "};")
    L.append("static const uint8_t BAR_TUBEG_I[BAR_NBAND][BAR_NFAM] = {" + ",".join(cvals(b) for b in idx["BAR_TUBEG"]) + "};")
    L += ["#endif", ""]
    return "\n".join(L)


def main():
    a = sys.argv[1:]
    src, out = SRC, OUT
    if "--src" in a:
        src = Path(a[a.index("--src") + 1])
    if "--out" in a:
        out = Path(a[a.index("--out") + 1]) / "bars_pack.h"
    h = header(src.read_text())
    if "--check" in a:
        ok = out.exists() and out.read_text() == h
        print("bars_pack.h: " + ("current" if ok else "OUT OF DATE (run tools/gen_bars_pack.py)"))
        return 0 if ok else 1
    out.write_text(h)
    print(f"wrote {out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
