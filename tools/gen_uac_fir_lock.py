"""firmware/src/uac_fir_lock.h: the polyphase FIR of the locked USB audio stream (usb.c FELUCCA_UAC_LOCK 1).

The same prototype as uac_fir.h (a Kaiser-windowed sinc, beta 7.5, cut-off 20000 Hz at 44.1 kHz in, 12 taps per
phase) at 16 times the phases: 2560 a 44.1 kHz frame instead of 160, so the stream can be read at any position
(the 48 kHz rate, the 44.1 kHz rate, and the FM-1's clock drift between them) with the nearest phase within 1/5120
of a frame; usb.c takes the rest out with a first-order correction. Each phase's taps are scaled to sum to exactly
1.0 (32768, Q15: no gain ripple from phase to phase), the rounding's remainder on the taps that lost the most.
Phase 2559 - p is phase p backwards: only phases 0..1279 are stored. Taps oldest input first.

    python3 tools/gen_uac_fir_lock.py        (writes the header; tests/py/test_uac_lock.py checks it is current)
"""
import os
import sys

import numpy as np

L, N, BETA, FC, FS = 2560, 12, 7.5, 20000.0, 44100.0
ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
OUT = os.path.join(ROOT, "firmware", "src", "uac_fir_lock.h")


def table():
    n = np.arange(N * L)
    h = (2 * FC / FS) * np.sinc(2 * FC / (L * FS) * (n - (N * L - 1) / 2.0)) * np.kaiser(N * L, BETA)
    t = np.array([[h[(N - 1 - k) * L + j] for k in range(N)] for j in range(L // 2)])
    t = t / t.sum(1, keepdims=True) * 32768
    q = np.round(t).astype(np.int64)
    for j in range(L // 2):
        e = int(32768 - q[j].sum())
        if e:
            order = np.argsort(-(t[j] - q[j]) * np.sign(e))
            for k in order[:abs(e)]:
                q[j, k] += np.sign(e)
    return q


def text(q):
    rows = ",\n".join("    {" + ", ".join(str(int(v)) for v in r) + "}" for r in q)
    return ("/* SPDX-License-Identifier: GPL-3.0-only */\n"
            "/* generated by tools/gen_uac_fir_lock.py: do not edit. The locked USB audio stream's polyphase FIR (usb.c,\n"
            " * FELUCCA_UAC_LOCK 1): L 2560 phases a 44.1 kHz frame, 12 taps per phase, Kaiser beta 7.5, cut-off 20000 Hz,\n"
            " * Q15, each phase summing to 32768; phases 0..1279 (phase 2559 - p = phase p backwards), taps oldest input\n"
            " * first. */\n"
            "#define UAC_FL_L 2560u\n#define UAC_FL_N 12u\n#define UAC_FL_Q 15\n"
            f"static const int16_t UAC_FL[{L // 2}][{N}] = {{\n{rows}\n}};\n")


if __name__ == "__main__":
    s = text(table())
    if "--check" in sys.argv:
        sys.exit(0 if open(OUT).read() == s else 1)
    open(OUT, "w").write(s)
    print(OUT, len(s), "bytes")
