"""Constant tables for the DRIVE's TYPEs (firmware/src/drive.c, drv_<type>.c): -> firmware/gen/drive_tables.h

Deterministic (integers from fixed formulas, no randomness, no file but this one's inputs) and checked against the chip
ROM window as gen_fx_tables.py does. The shared part:

  DRV_TANH_H[257]   the running integral of fx_tables.h FX_TANH (the classic drive's curve), for drv_adaa1: any TYPE
                    may use tanh with anti-aliasing at no flash cost for the curve itself

and the helpers a TYPE's section uses:

  curve(name, f, half, sh)   a curve f(x) sampled at 2 half + 1 points (x = (i - half) 2^sh in the TYPE's input
                             units), Q15 -> NAME_F (int16), and its integral -> NAME_H (int32), drive.c drv_curve /
                             drv_curve_p / drv_adaa1
  bq_q28(b, a, fc_warp)      an analog biquad b(s) / a(s) -> drive.c drv_bq_t {b0, b1, b2, a1, a2} (Q28, a negated),
                             bilinear, prewarped at fc_warp (Hz) when given
  tpt_g30(fc)                drive.c drv_tpt1's G = g / (1 + g), g = tan(pi fc / fs), Q30
  rows(name, ctype, rows)    a table of rows (e.g. one biquad per AMOUNT step)

A TYPE's tables come from TYPE_SECTIONS: tools/drive_gen/<type>.py, if it exists, defines tables() -> a list of
the strings these helpers return (one file per TYPE, as in the firmware).
"""
import importlib.util
import math
import os

FS = 44100.0
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "firmware", "gen", "drive_tables.h")
ROM_LO, ROM_HI = 0xFFC00000, 0xFFCFFFFF
TYPE_SECTIONS = ["aa", "khlon", "tsh8", "ohcd", "bhlue"]   # (aa: the shared anti-aliasing tables)       # drive.c's TYPEs 2..5, in that order


def check(name, vals):
    for v in vals:
        assert isinstance(v, int), (name, v)
        assert not (ROM_LO <= (v & 0xFFFFFFFF) <= ROM_HI), (name, v)     # never an address in the chip ROM


def arr(name, ctype, vals, per=16):
    check(name, vals)
    rows = [",".join(str(v) for v in vals[i:i + per]) for i in range(0, len(vals), per)]
    return f"static const {ctype} {name}[{len(vals)}] = {{\n  " + ",\n  ".join(rows) + "\n};\n"


def rows(name, ctype, rs):
    for r in rs:
        check(name, r)
    body = ",\n  ".join("{" + ",".join(str(v) for v in r) + "}" for r in rs)
    return f"static const {ctype} {name}[{len(rs)}] = {{\n  {body}\n}};\n"


def integral(f):
    """h[i] = c + sum_{j < i} (f[j] + f[j + 1]): drive.c drv_curve_p's running integral (2^(1 - sh) x the true one),
    c = the constant that makes the smallest 0 (only differences count; every value >= 0 is clear of the ROM window)"""
    h, s = [0], 0
    for j in range(len(f) - 1):
        s += f[j] + f[j + 1]
        h.append(s)
    lo = min(h)
    h = [v - lo for v in h]
    assert max(h) < 2 ** 31
    return h


def curve(name, fn, half, sh):
    """fn(x) -> a value in [-1, 1] at x = (i - half) 2^sh: NAME_F (Q15) and NAME_H; returns the C text"""
    assert sh <= 14 and half >= 1
    f = [max(-32767, min(32767, int(round(32767 * fn((i - half) * 2 ** sh))))) for i in range(2 * half + 1)]
    return arr(f"{name}_F", "int16_t", f) + arr(f"{name}_H", "int32_t", integral(f), 8)


def q(v, bits):
    r = int(round(v * (1 << bits)))
    assert -(1 << 31) <= r < (1 << 31), (v, bits)
    return r


def bq_q28(b, a, fc_warp=None):
    """b(s) = b[0] s^2 + b[1] s + b[2], a(s) the same (a[0] != 0) -> [b0, b1, b2, -a1, -a2] (Q28), bilinear with
    s = K (1 - z^-1) / (1 + z^-1), K = 2 fs (or w / tan(w / 2 fs) to land fc_warp exactly)"""
    K = 2 * FS if not fc_warp else 2 * math.pi * fc_warp / math.tan(math.pi * fc_warp / FS)
    B = [b[0] * K * K + b[1] * K + b[2], 2 * (b[2] - b[0] * K * K), b[0] * K * K - b[1] * K + b[2]]
    A = [a[0] * K * K + a[1] * K + a[2], 2 * (a[2] - a[0] * K * K), a[0] * K * K - a[1] * K + a[2]]
    c = [B[0] / A[0], B[1] / A[0], B[2] / A[0], -A[1] / A[0], -A[2] / A[0]]
    assert all(abs(x) < 8 for x in c), c
    return [q(x, 28) for x in c]


def tpt_g30(fc):
    g = math.tan(math.pi * fc / FS)
    return q(g / (1 + g), 30)


def fx_tanh():
    """fx_tables.h FX_TANH, the same formula as gen_fx_tables.py (tests/py/test_drive_core.py checks it is the same)"""
    return [int(round(32767 * math.tanh(-4 + i / 32))) for i in range(257)]


def type_tables(name):
    p = os.path.join(ROOT, "tools", "drive_gen", f"{name}.py")
    if not os.path.exists(p):
        return []
    spec = importlib.util.spec_from_file_location(f"drive_gen_{name}", p)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod.tables()


def text():
    out = ["/* SPDX-License-Identifier: GPL-3.0-only */",
           "/* GENERATED by tools/gen_drive_tables.py - do not edit. */", ""]
    out.append("/* the integral of FX_TANH (fx_tables.h): drv_adaa1(s, FX_TANH, DRV_TANH_H, 128, 10, eps, x) is the "
               "classic\n * drive's softclip (x Q15, +-4) with anti-aliasing */")
    out.append(arr("DRV_TANH_H", "int32_t", integral(fx_tanh()), 8))
    for t in TYPE_SECTIONS:
        tabs = type_tables(t)
        if tabs:
            out.append(f"/* ---- {t.upper()} (tools/drive_gen/{t}.py) */")
            out += tabs
    return "\n".join(out)


def main():
    open(OUT, "w").write(text())
    print("wrote", os.path.relpath(OUT, ROOT))


if __name__ == "__main__":
    main()
